    def _ensure_memory_injection(self) -> None:
        """Ensure memory is injected as the first system message if needed."""
        from parllama.memory_manager import memory_manager

        # Only inject memory if:
        # 1. Memory is enabled and has content
        # 2. This is a new conversation (no user messages exist yet)
        # 3. Memory hasn't already been injected
        if not memory_manager.is_memory_enabled:
            return

        # Check if we have any user or assistant messages (indicating conversation has started)
        has_conversation_messages = any(msg.role in ("user", "assistant") for msg in self.messages)

        # Check if memory is already injected (look for system message with memory content)
        memory_content = memory_manager.get_memory_for_injection()
        if not memory_content:
            return

        # Check if memory is already present in existing system messages
        memory_already_present = any(
            msg.role == "system" and memory_content.strip() in msg.content for msg in self.messages
        )

        # Only inject if this is a new conversation and memory isn't already present
        if not has_conversation_messages and not memory_already_present:
            # Create memory system message
            memory_message = ParllamaChatMessage(
                role="system",
                content=f"User Memory (remember this context for the entire conversation):\n\n{memory_content}",
            )

            # Add as the first message, but after any existing system prompt
            existing_system_msg = self.system_prompt
            if existing_system_msg:
                # If there's already a system prompt, prepend memory to it
                combined_content = f"{memory_message.content}\n\n---\n\n{existing_system_msg.content}"
                existing_system_msg.content = combined_content
                self._changes.add("system_prompt")
                self._changes.add("messages")
                self.save()
            else:
                # No existing system message, add memory as new system message
                self.add_message(memory_message, prepend=True)

    def _maybe_trigger_auto_naming(self, is_aborted: bool) -> None:
        """Request an LLM-generated session name if auto-naming is enabled and due.

        Args:
            is_aborted: Whether the generation that just completed was aborted;
                auto-naming is skipped in that case.
        """
        if is_aborted or not settings.chat.auto_name_session or not settings.chat.auto_name_session_llm_config:
            return
        if self.name_generated:
            return

        self.name_generated = True
        user_msg = self.get_first_user_message()
        ai_msg = self.get_first_ai_message()
        if user_msg and ai_msg and user_msg.content and ai_msg.content:
            self.log_it("Auto naming session", notify=True)
            app = self.app or (self.parent.app if self.parent else None)
            if app:
                app.post_message(
                    SessionAutoNameRequested(
                        session_id=self.id,
                        llm_config=LlmConfig.from_json(settings.chat.auto_name_session_llm_config),
                        context=f"#USER\n{user_msg.content}\n\n#ASSISTANT\n{ai_msg.content}",
                    )
                )

    _thinking_capability_cache: ClassVar[dict[str, bool]] = {}
    """Model name → whether the Ollama model declares the 'thinking' capability."""

    def _model_supports_thinking(self) -> bool:
        """Whether the session's Ollama model declares the 'thinking' capability."""
        name = self._llm_config.model_name
        cached = ChatSession._thinking_capability_cache.get(name)
        if cached is not None:
            return cached
        try:
            from parllama.ollama_data_manager import ollama_dm

            info = ollama_dm.ollama_client.show(name)
            supported = "thinking" in (info.get("capabilities") or [])
        except Exception as e:  # noqa: BLE001
            self.log_it(f"Could not query model capabilities for {name}: {e}")
            supported = False
        ChatSession._thinking_capability_cache[name] = supported
        return supported

    def _build_stream_chat_model(self) -> Any:
        """Build the chat model for streaming, enabling reasoning passthrough
        for Ollama thinking models.

        Without ``reasoning=True`` langchain-ollama discards the model's
        thinking output entirely: the model still thinks (its chat template
        forces it), but every chunk arrives empty and a long reasoning phase
        looks like a hang.
        """
        chat_model = self._llm_config.build_chat_model()
        if self._llm_config.provider == LlmProvider.OLLAMA and self._model_supports_thinking():
            # ChatOllama exposes a `reasoning` field; guarded with hasattr so
            # the type stays BaseChatModel for every other provider.
            if hasattr(chat_model, "reasoning"):
                chat_model.reasoning = True  # pyright: ignore [reportAttributeAccessIssue]
        return chat_model

    def _effective_ctx_budget(self) -> int:
        """The context window the request will actually run in: the session's
        ``num_ctx`` when set, else the model's configured window (for Ollama
        that is where the server silently truncates the prompt), else a
        conservative default."""
        if self._llm_config.num_ctx:
            return self._llm_config.num_ctx
        from parllama.provider_manager import provider_manager

        return (
            provider_manager.get_model_context_length(self._llm_config.provider, self._llm_config.model_name)
            or TOKEN_WARN_THRESHOLD
        )

    def _document_text_char_cap(self) -> int | None:
        """Per-document character cap that keeps room for the response.

        Documents are pre-truncated client-side so the prompt leaves reserve
        for the model's reply — thinking models need far more headroom than
        a plain answer. None when the documents already fit.
        """
        docs = [d for m in self.messages if m.documents for d in m.documents]
        if not docs:
            return None

        budget = self._effective_ctx_budget()
        reserve = 4096 if self._model_supports_thinking() else 1024
        reserve = min(reserve, budget // 2)

        conv_tokens = sum((len(m.content) + len(m.thinking)) // 4 for m in self.messages)
        doc_tokens = sum(estimate_document_tokens(d) for d in docs)
        available = budget - reserve - conv_tokens
        if available >= doc_tokens:
            return None
        return max(available // len(docs), 0) * 4

    def _prepare_document_budget(self) -> int | None:
        """Compute the send-time document cap and toast when it bites."""
        cap = self._document_text_char_cap()
        if cap is None:
            return None
        names = ", ".join(d.name for m in self.messages if m.documents for d in m.documents)
        self.log_it(
            f"Truncated {names} to fit the model context window (raise Max Context Size for the full document)",
            notify=True,
            severity="warning",
        )
        return cap

    def _open_stream(self) -> Iterator[BaseMessageChunk]:
        """Build the chat history (with the send-time document budget) and open the provider stream."""
        doc_text_char_cap = self._prepare_document_budget()
        chat_history = [
            m.to_langchain_native(self._llm_config.provider, doc_text_char_cap=doc_text_char_cap) for m in self.messages
        ]
        chat_model = self._build_stream_chat_model()
        return chat_model.stream(
            chat_history,  # type: ignore
            config=llm_run_manager.get_runnable_config(chat_model.name or ""),
        )

    async def send_chat(
        self,
        from_user: str,
        images: list[str] | None = None,
        documents: list[DocumentAttachment] | None = None,
    ) -> bool:
        """Send a chat message to the configured LLM and stream the response.

        Appends the user's message (if any) to the session, then streams the
        assistant's reply from the configured LLM, updating the in-progress
        assistant message as chunks arrive. Handles user-initiated aborts and
        provider errors, persists the session, and may trigger auto-naming.

        Args:
            from_user: The user's message content to send. Pass an empty
                string to continue generation without adding a new user
                message (e.g. when regenerating a response).
            images: Optional image paths/URLs to attach to the user message.
            documents: Optional documents to attach to the user message.

        Returns:
            True if generation completed normally; False if it was aborted
            by the user or failed with an error.
        """
        self._generating = True
        is_aborted = False
        msg: ParllamaChatMessage | None = None
        try:
            if not self._llm_config.model_name.strip():
                self.log_it(
                    "No model selected for this session — pick one in the session config", notify=True, severity="error"
                )
                return False

            # Check if we need to inject memory at the start of conversation
            self._ensure_memory_injection()

            if from_user:
                # self.log_it("CM adding user message")
                msg = ParllamaChatMessage(role="user", content=from_user, images=images, documents=documents)
                self.add_message(msg)
                self._emit(ChatMessage(parent_id=self.id, message_id=msg.id, is_final=True))
                self.save()

            start_time = datetime.now(UTC)
            stream = self._open_stream()
            msg = ParllamaChatMessage(role="assistant")
            self.add_message(msg)
            self._emit(ChatMessage(parent_id=self.id, message_id=msg.id))
            is_aborted = self._stream.run(stream, msg, start_time).aborted

            if not is_aborted:
                # Guarantee the terminal render even when the provider's last
                # yielded chunk carries no done marker.
                self._emit(ChatMessage(parent_id=self.id, message_id=msg.id, is_final=True))
            self._stream.append_finish_reason_note(msg)
            self._accumulate_cost()
            self._changes.add("messages")
            self.save()

            self._maybe_trigger_auto_naming(is_aborted)
        except Exception as e:  # noqa: BLE001
            self.log_it(f"Chat generation error ({type(e).__name__}): {e}")
            self.log_it("Error generating message", notify=True, severity="error")
            if msg is not None:
                err_msg = StreamController.parse_llm_error(str(e))

                msg.content += f"\n\n{err_msg}"
                msg.content = msg.content.strip()
                self._changes.add("messages")
                self.save()
                self._emit(ChatMessage(parent_id=self.id, message_id=msg.id, is_final=True))
                return False
        finally:
            self._generating = False

        return not is_aborted

    def new_session(self, name: str = "My Chat"):
        """Start new session"""
        self._batching = True
        self.id = uuid.uuid4().hex
        self.name = name
        self.name_generated = False
        self.messages.clear()
        self._id_to_msg.clear()
        self.clear_changes()
        self._loaded = False
        self._stream.reset_stats()
        self._batching = False

    def __eq__(self, other: object) -> bool:
        """Check if two sessions are equal"""
        if not isinstance(other, ChatSession):
            return NotImplemented
        return self.id == other.id

    def __ne__(self, other: object) -> bool:
        """Check if two sessions are not equal"""
        if not isinstance(other, ChatSession):
            return NotImplemented
        return self.id != other.id

    def to_json(self) -> str:
        """Serialize the chat session to a JSON string.

        Returns:
            A JSON string containing session metadata, encrypted salt/key
            fields (if a password is set), cost/usage tracking, and all
            messages. Suitable for round-tripping through :meth:`from_json`.
        """
        return json.dumps(SessionStore.serialize(self), str, json.OPT_INDENT_2).decode("utf-8")

    @staticmethod
    def from_json(json_data: str, load_messages: bool = False) -> ChatSession:
        """Build a ChatSession from its JSON string representation.

        Supports both the current session format and older formats (e.g.
        sessions saved before ``llm_config`` was introduced).

        Args:
            json_data: The session data as a JSON string, as produced by
                :meth:`to_json`.
            load_messages: Whether to parse and attach the session's messages.
                Pass False to load session metadata only (faster for listing).

        Returns:
            The reconstructed ChatSession instance.

        Raises:
            orjson.JSONDecodeError: If ``json_data`` is not valid JSON.
            KeyError: If required fields (e.g. ``last_updated``) are missing.
        """
        data: dict = json.loads(json_data)
        messages = SessionStore.normalize_legacy_messages(data["messages"]) if load_messages else []
        utc = pytz.UTC
        lc = data.get("llm_config")
        # adapt old format session
        if not lc:
            lc = LlmConfig(
                provider=LlmProvider.OLLAMA,
                model_name=data["llm_model_name"],
                temperature=data.get("options", {}).get("temperature", 0.5),
            ).to_json()
        session = ChatSession(
            id=data.get("id", data.get("id", data.get("session_id"))),
            name=data.get("name", data.get("name", data.get("session_name"))) or "Session",
            last_updated=datetime.fromisoformat(data["last_updated"]).replace(tzinfo=utc),
            messages=([ParllamaChatMessage(**m) for m in messages] if load_messages else None),
            llm_config=LlmConfig.from_json(lc),
        )
        session.name_generated = True

        if salt := data.get("__salt__"):
            session._salt = base64.b64decode(salt)
        else:
            session._salt = None

        session._key_secure = data.get("__key__")

        session._total_cost = data.get("total_cost", 0.0)
        session._total_usage = data.get("total_usage", {"input_tokens": 0, "output_tokens": 0, "total_tokens": 0})

        return session

    @staticmethod
    def load_from_file(filename: str) -> ChatSession | None:
        """Load a chat session from a JSON file in the configured chat directory.

        Args:
            filename: The session file's name (e.g. ``"<id>.json"``), relative
                to ``settings.chat_dir``.

        Returns:
            The loaded ChatSession, or None if the file is missing, fails
            security validation, or cannot be read.
        """
        try:
            return ChatSession.from_json(SessionStore().read_text(filename))
        except (OSError, SecureFileOpsError):
            return None

    @property
    def is_valid(self) -> bool:
        """return true if session is valid"""
        return (
            len(self.name) > 0 and len(self.llm_model_name) > 0 and self.llm_model_name not in ["Select.NULL", "None"]
            # and len(self.messages) > 0
        )

    def save(self) -> bool:
        """Persist the chat session to disk, if there are unsaved changes to save.

        Notifies listeners of what changed, then atomically writes the
        session to its JSON file. Saving is skipped while batching, when
        there are no pending changes, when ``settings.no_save_chat`` is set,
        or when the session is not yet valid (missing name/model or empty).

        Returns:
            True if the session was written to disk; False if saving was
            skipped or failed.
        """
        if self._batching:
            # self.log_it(f"CS is batching, not notifying: {self.name}")
            return False
        if not self._loaded:
            self.load()
        if not self.is_dirty:
            # self.log_it(f"CS is not dirty, not notifying: {self.name}")
            return False  # No need to save if no changes

        self.last_updated = datetime.now(UTC)
        if "system_prompt" in self._changes:
            msg = self.system_prompt
            if msg is not None:
                self._emit(ChatMessage(parent_id=self.id, message_id=msg.id))
        nc: SessionChanges = set()
        for change in self._changes:
            if change in session_change_list:
                nc.add(change)  # type: ignore

        self._notify_changed(nc)
        self.clear_changes()

        if settings.no_save_chat:
            return False  # Do not save if no_save_chat is set in settings
        if not self.is_valid or len(self.messages) == 0:
            # self.log_it(f"CS not valid, not saving: {self.id}")
            return False  # Cannot save without name, LLM model name and at least one message

        try:
            self._store.write(self)
            return True
        except (OSError, SecureFileOpsError) as e:
            self.log_it(f"Error saving session: {e}", notify=True, severity="error")
            return False

    def stop_generation(self) -> None:
        """Stop LLM model generation"""
        self._stream.request_abort()

    async def continue_generation(self, message_id: str) -> bool:
        """Continue generation from an edited assistant message.

        Strips any trailing abort suffix from the message, removes
        any messages that follow it, and appends streamed content to
        the existing message.

        Args:
            message_id: The id of the assistant message to continue from.

        Returns:
            True if generation completed normally; False if a generation was
            already in progress, ``message_id`` was not found or was not an
            assistant message, or generation was aborted.
        """
        if self._generating:
            return False

        msg = self[message_id]
        if msg is None or msg.role != "assistant":
            return False

        # Must run before any mutation: the deletions below are persisted immediately.
        if not self._llm_config.model_name.strip():
            self.log_it(
                "No model selected for this session — pick one in the session config", notify=True, severity="error"
            )
            return False

        # Strip abort suffix if present
        if msg.content.endswith(self.ABORT_SUFFIX):
            msg.content = msg.content[: -len(self.ABORT_SUFFIX)]

        # Remove all messages after the continued message
        idx = next((i for i, m in enumerate(self.messages) if m.id == message_id), -1)
        if idx == -1:
            return False

        self._generating = True
        removed_ids = [m.id for m in self.messages[idx + 1 :]]
        self.messages = self.messages[: idx + 1]
        for rid in removed_ids:
            if rid in self._id_to_msg:
                del self._id_to_msg[rid]
                self._emit(ChatMessageDeleted(parent_id=self.id, message_id=rid))

        self._changes.add("messages")
        self.save()
        is_aborted = False
        try:
            self._ensure_memory_injection()

            start_time = datetime.now(UTC)
            stream = self._open_stream()
            self._emit(ChatMessage(parent_id=self.id, message_id=msg.id, is_final=False))
            result = self._stream.run(stream, msg, start_time)
            is_aborted = result.aborted
            if result.errored:
                self._emit(ChatMessage(parent_id=self.id, message_id=msg.id, is_final=True))

            if not is_aborted:
                self._emit(ChatMessage(parent_id=self.id, message_id=msg.id, is_final=True))
            self._stream.append_finish_reason_note(msg)
            self._accumulate_cost()
            self._changes.add("messages")
            self.save()

        except Exception as e:  # noqa: BLE001
            self.log_it(f"Continue generation error ({type(e).__name__}): {e}")
            self.log_it("Error generating message", notify=True, severity="error")
            err_msg = StreamController.parse_llm_error(str(e))
            msg.content += f"\n\n{err_msg}"
            msg.content = msg.content.strip()
            self._changes.add("messages")
            self.save()
            self._emit(ChatMessage(parent_id=self.id, message_id=msg.id, is_final=True))
            return False
        finally:
            self._generating = False

        return not is_aborted

    @property
    def abort_pending(self) -> bool:
        """Check if LLM model generation is pending"""
        return self._stream.abort_pending

    @property
    def is_generating(self) -> bool:
        """Check if LLM model generation is in progress"""
        return self._generating

    def check_consecutive_messages(self) -> None:
        """Checks for consecutive user or assistant messages in a session and merges them."""

        if len(self.messages) <= 1:
            return

        new_messages: list[ParllamaChatMessage] = []
        previous_role: MessageRoles | None = None
        current_message: ParllamaChatMessage | None = None

        for message in self.messages:
            if message.role == previous_role:
                if current_message:
                    current_message.content += "\n" + message.content
                    if message.thinking:
                        current_message.thinking += ("\n" if current_message.thinking else "") + message.thinking
                    if message.images:
                        if not current_message.images:
                            current_message.images = []
                        current_message.images.extend(message.images)
                    if message.documents:
                        if not current_message.documents:
                            current_message.documents = []
                        current_message.documents.extend(message.documents)
                    if message.tool_calls:
                        if not current_message.tool_calls:
                            current_message.tool_calls = []
                        current_message.tool_calls.extend(message.tool_calls)  # type: ignore
            else:
                if current_message:
                    new_messages.append(current_message)
                # Keep the first message's id of each run so existing widget
                # references and id-keyed lookups survive the merge.
                current_message = ParllamaChatMessage(
                    id=message.id,
                    role=message.role,
                    content=message.content,
                    thinking=message.thinking,
                    images=message.images,
                    tool_calls=message.tool_calls,
                    documents=message.documents,
                )
                previous_role = message.role

        if current_message:
            new_messages.append(current_message)

        if len(new_messages) != len(self.messages):
            self.messages.clear()
            self._id_to_msg.clear()
            for message in new_messages:
                self.add_message(message)
