@rich.repr.auto
@dataclass
class ChatSession(ChatMessageContainer):
    """Chat session class"""

    ABORT_SUFFIX = StreamController.ABORT_SUFFIX

    name_generated: bool
    """Set to True if the session name has been generated by LLM"""
    _generating: bool
    """Set to True if the session is currently generating"""
    _batching: bool
    """Set to True if the session is currently being batched"""
    _stream: StreamController
    """Streaming engine: chunk assembly, stats, abort and error handling"""
    _store: SessionStore
    """Session file serialization and persistence"""
    _total_cost: float
    """Cumulative session cost in USD"""
    _total_usage: dict[str, int | float]
    """Cumulative token usage across all responses"""
    _llm_config: LlmConfig
    """LLM configuration"""
    _key_secure: str | None
    """Encrypted current session password"""
    _key: bytes | None
    """Decryption key derived from the password."""
    _salt: bytes | None
    """Used with password to derive the en/decryption key."""

    def __init__(
        self,
        *,
        id: str | None = None,
        name: str,
        llm_config: LlmConfig,
        messages: list[ParllamaChatMessage] | list[dict] | None = None,
        last_updated: datetime | None = None,
    ):
        """Initialize the chat session"""
        super().__init__(id=id, name=name, messages=messages, last_updated=last_updated)
        self._batching = False
        self._salt = None
        self._key = None
        self._key_secure = None
        self.name_generated = False
        self._generating = False
        self._total_cost = 0.0
        self._total_usage = {
            "input_tokens": 0,
            "output_tokens": 0,
            "total_tokens": 0,
        }
        self._llm_config = llm_config
        self._stream = StreamController(self)
        self._store = SessionStore()

    @property
    def llm_config(self) -> LlmConfig:
        """Return the LLM configuration"""
        return self._llm_config

    def load(self) -> None:
        """Load chat sessions from files"""
        if self._loaded:
            self._batching = False
            return

        self._batching = True
        try:
            self._stream.reset_stats()
            data = self._store.read(self.id)
            if data is None:
                return

            # Update session properties from loaded data
            if "name" in data:
                self.name = data["name"]
            if "name_generated" in data:
                self.name_generated = data["name_generated"]
            if "_salt" in data and data["_salt"]:
                self._salt = base64.b64decode(data["_salt"])
            if "__key__" in data:
                self._key_secure = data["__key__"]

            # Update llm_config from loaded data
            if "llm_config" in data:
                lc = data["llm_config"]
                if isinstance(lc, str):
                    lc_dict = json.loads(lc)
                    self._llm_config = LlmConfig.from_json(lc_dict)
                elif isinstance(lc, dict):
                    self._llm_config = LlmConfig.from_json(lc)

            # Restore cost and usage tracking
            self._total_cost = data.get("total_cost", 0.0)
            self._total_usage = data.get("total_usage", {"input_tokens": 0, "output_tokens": 0, "total_tokens": 0})

            # Load messages
            msgs = SessionStore.normalize_legacy_messages(data["messages"] or [])
            for m in msgs:
                self.add_message(ParllamaChatMessage(**m))
            self._loaded = True
        except (Exception, SecureFileOpsError) as e:  # noqa: BLE001
            self.log_it(f"Error loading session {e}", notify=True, severity="error")
        finally:
            self._batching = False
            self.clear_changes()

    def _emit(self, event: Message) -> None:
        """Emit a Textual message through the owning app."""
        app = self.app or (self.parent.app if self.parent else None)
        if app:
            app.post_message(event)

    def delete(self) -> None:
        """Delete the session"""
        self._emit(DeleteSession(session_id=self.id))

    def _notify_changed(self, changed: SessionChanges) -> None:
        """Notify changed"""
        self._emit(SessionUpdated(session_id=self.id, changed=changed))

    @property
    def stats(self) -> TokenStats | None:
        """Get the chat session stats"""
        return self._stream.stats

    @property
    def total_cost(self) -> float:
        """Get cumulative session cost in USD"""
        return self._total_cost

    @property
    def total_usage(self) -> dict[str, int | float]:
        """Get cumulative token usage"""
        return self._total_usage

    def _accumulate_cost(self) -> None:
        """Calculate and accumulate cost from latest streaming stats."""
        stats = self._stream.stats
        if not stats:
            return
        usage_metadata: dict[str, int | float] = {
            "input_tokens": stats.input_tokens,
            "output_tokens": stats.output_tokens,
            "total_tokens": stats.total_tokens,
            "cache_write": 0,
            "cache_read": 0,
        }
        from par_ai_core.pricing_lookup import get_api_call_cost

        cost = get_api_call_cost(llm_config=self._llm_config, usage_metadata=usage_metadata)
        self._total_cost += cost
        self._total_usage["input_tokens"] += stats.input_tokens
        self._total_usage["output_tokens"] += stats.output_tokens
        self._total_usage["total_tokens"] += stats.total_tokens

    def __str__(self) -> str:
        """Get markdown representation with YAML frontmatter."""
        from io import StringIO

        usage = self._total_usage
        lines = [
            "---",
            f"provider: {self._llm_config.provider.value}",
            f"model: {self._llm_config.model_name}",
            f"context_window: {self._llm_config.num_ctx or ''}",
            f"temperature: {self._llm_config.temperature}",
            f"date: {self.last_updated.isoformat()}",
            f"input_tokens: {usage['input_tokens']}",
            f"output_tokens: {usage['output_tokens']}",
            f"total_tokens: {usage['total_tokens']}",
            f"cost: {self._total_cost:.6f}",
            "---",
            "",
            f"# {self.name}",
            "",
        ]
        ret = StringIO()
        ret.write("\n".join(lines))
        for msg in self.messages:
            ret.write(str(msg))
        return ret.getvalue()

    @property
    def llm_provider_name(self) -> LlmProvider:
        """Get the LLM model name"""
        return self._llm_config.provider

    @llm_provider_name.setter
    def llm_provider_name(self, value: LlmProvider) -> None:
        """Set the LLM model name"""
        if self._llm_config.provider == value:
            return
        self._llm_config.provider = value
        self._stream.reset_stats()
        self._changes.add("provider")
        self._changes.add("model")
        self.save()

    @property
    def llm_model_name(self) -> str:
        """Get the LLM model name"""
        return self._llm_config.model_name

    @llm_model_name.setter
    def llm_model_name(self, value: str) -> None:
        """Set the LLM model name"""
        value = value.strip()
        if self._llm_config.model_name == value:
            return
        self._llm_config.model_name = value
        self._stream.reset_stats()
        self._changes.add("model")
        self.save()

