"""ARC-002: settings.json schema versioning, v1 flat -> v2 nested migration, and round-tripping."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from par_ai_core.llm_config import LlmConfig, LlmMode
from par_ai_core.llm_providers import LlmProvider

from parllama.settings.migration import SCHEMA_VERSION, migrate_settings_data
from parllama.settings_manager import Settings, apply_settings_data

FIXTURE = Path(__file__).parent / "fixtures" / "settings_flat_v1.json"


def _settings_at(tmp_path: Path) -> Settings:
    s = Settings()
    s.data_dir = tmp_path
    s.settings_file = tmp_path / "settings.json"
    return s


def _load_fixture(tmp_path: Path) -> Settings:
    shutil.copy(FIXTURE, tmp_path / "settings.json")
    s = _settings_at(tmp_path)
    s.load_from_file()
    return s


def test_v1_flat_file_loads_every_group(tmp_path: Path) -> None:
    """A real v1 flat settings.json (generated by the pre-ARC-002 code) restores values in every group."""
    s = _load_fixture(tmp_path)

    assert s.ollama.ollama_host == "http://ollama.example:11434"
    assert s.ollama.local_model_sort == "name_asc"
    assert s.provider.provider_api_keys[LlmProvider.OPENAI] == "sk-fixture-openai"
    assert s.provider.provider_api_keys[LlmProvider.ANTHROPIC] is None
    assert s.provider.provider_cache_hours[LlmProvider.GROQ] == 6
    assert s.provider.disabled_providers[LlmProvider.XAI] is True
    assert s.ui.theme_name == "custom"
    assert s.ui.theme_mode == "light"
    assert s.ui.show_first_run is False
    assert s.ui.notification_timeout_error == 7.5
    assert s.chat.chat_tab_max_length == 22
    assert s.chat.save_chat_input_history is True
    assert s.execution.execution_allowed_commands == ["uv", "python3"]
    assert s.retry.max_retry_attempts == 5
    assert s.timer.job_queue_max_size == 300
    assert s.timer.ps_timer_interval == 2.0
    assert s.http.provider_model_request_timeout == 12.0
    assert s.file_validation.max_pdf_pages == 77
    assert s.file_validation.allowed_document_extensions == [".pdf", ".rst"]
    assert s.memory.user_memory == "I like tea."
    assert s.memory.memory_enabled is False
    assert s.last_tab == "Chat"
    assert s.last_chat_session_id == "sess-123"
    assert s.max_log_lines == 2500
    assert s.langchain_config.project == "fixture-project"
    assert s.last_version_check is not None and s.last_version_check.year == 2026


def test_v1_legacy_keys_are_migrated(tmp_path: Path) -> None:
    """starting_screen, last_chat_*, disable_litellm_provider and string enums in auto-name config migrate."""
    s = _load_fixture(tmp_path)

    assert s.starting_tab == "Prompts"
    assert s.last_llm_config.provider == LlmProvider.ANTHROPIC
    assert s.last_llm_config.model_name == "claude-legacy"
    assert s.last_llm_config.temperature == 0.9
    assert s.provider.disabled_providers[LlmProvider.LITELLM] is True
    assert s.chat.auto_name_session_llm_config is not None
    cfg = LlmConfig.from_json(s.chat.auto_name_session_llm_config)
    assert cfg.provider == LlmProvider.GROQ
    assert cfg.mode == LlmMode.CHAT
    assert cfg.model_name == "llama-fixture"


def test_v1_runtime_paths_in_file_are_ignored(tmp_path: Path) -> None:
    """Paths stored by v1 (data_dir, cache_dir, execution paths) never override the startup-derived layout."""
    s = _load_fixture(tmp_path)
    assert s.data_dir == tmp_path
    assert s.settings_file == tmp_path / "settings.json"
    assert s.execution.execution_temp_dir == Path()


def test_save_after_v1_load_writes_nested_v2(tmp_path: Path) -> None:
    """The first save after loading a v1 file rewrites it nested with schema_version, without runtime paths."""
    s = _load_fixture(tmp_path)
    s.save()

    on_disk = json.loads((tmp_path / "settings.json").read_text())
    assert on_disk["schema_version"] == SCHEMA_VERSION
    assert on_disk["ollama"]["ollama_host"] == "http://ollama.example:11434"
    assert on_disk["provider"]["provider_api_keys"]["OpenAI"] == "sk-fixture-openai"
    assert "ollama_host" not in on_disk
    assert "starting_screen" not in on_disk
    assert "disable_litellm_provider" not in on_disk
    for runtime in ("data_dir", "cache_dir", "chat_dir", "settings_file", "no_save"):
        assert runtime not in on_disk
    assert "execution_temp_dir" not in on_disk["execution"]


def test_v2_round_trip_is_lossless(tmp_path: Path) -> None:
    """Saving and reloading a v2 file reproduces every persisted value."""
    first = _load_fixture(tmp_path)
    first.save()
    second = _settings_at(tmp_path)
    second.load_from_file()

    assert second.to_file_data() == first.to_file_data()


def test_v2_data_is_not_migrated_again() -> None:
    nested = {"schema_version": SCHEMA_VERSION, "ollama": {"ollama_host": "http://x:1"}}
    assert migrate_settings_data(nested) is nested


def test_invalid_value_keeps_current_without_resetting_group() -> None:
    """One bad field is dropped on its own; its sibling fields in the same group still load."""
    s = Settings()
    apply_settings_data(
        s,
        {
            "schema_version": SCHEMA_VERSION,
            "ollama": {"ollama_host": "ftp://nope", "local_model_sort": "name_desc"},
            "retry": {"max_retry_attempts": "lots", "retry_max_delay": 0},
        },
    )
    assert s.ollama.ollama_host == "http://localhost:11434"
    assert s.ollama.local_model_sort == "name_desc"
    assert s.retry.max_retry_attempts == 3
    assert s.retry.retry_max_delay == 1.0


def test_unknown_provider_key_is_skipped_and_google_maps_to_gemini() -> None:
    s = Settings()
    apply_settings_data(
        s,
        {
            "schema_version": SCHEMA_VERSION,
            "provider": {"provider_api_keys": {"Google": "g-key", "NoSuchProvider": "x", "OpenAI": ""}},
        },
    )
    assert s.provider.provider_api_keys[LlmProvider.GEMINI] == "g-key"
    assert s.provider.provider_api_keys[LlmProvider.OPENAI] is None
    assert set(s.provider.provider_api_keys) >= {LlmProvider.OLLAMA, LlmProvider.GROQ}


def test_missing_auto_name_config_in_v1_gets_default() -> None:
    migrated = migrate_settings_data({"theme_name": "par"})
    assert migrated["chat"]["auto_name_session_llm_config"]["provider"] == "Ollama"
    assert migrated["ui"]["theme_name"] == "par"
